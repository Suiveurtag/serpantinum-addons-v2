#!/usr/bin/env python3
"""Copy Capri's art from an upstream capri-desktop checkout and derive what QML Canvas cannot
make at runtime (no offscreen canvases): the intro's flat silhouettes and colour channels, and
the sprite's hit-test alpha map. Usage: build-capri-assets.py [~/Projects/capri/upstream]"""
import json
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'payload/capri'
COPIED = (['capri-full.png'] + [f'cutin-{k}.png' for k in ('grin', 'laugh', 'eyes', 'many', 'look')]
          + [f'intro-{k}.webp' for k in ('grab', 'mouth1', 'mouth2', 'mouth3', 'wave1', 'wave2', 'wave3', 'smear', 'happy')])
FLATS = {'paper': '#fff4f6', 'ink': '#14101c', 'violet': '#7b3dff'}  # fx.js COLORS


def arm_l(x, y):  # sprite.js SPRITE.armL
    if x > 101 or y > 234: return False
    bot = 234 if x < 50 else 178 + (98 - x) * 0.62
    return 159 + (98 - x) * 0.5 <= y <= bot


def build(upstream):
    assets = upstream/'assets/capri'
    for name in COPIED:
        shutil.copy2(assets/name, OUT/'assets'/name)
    grab = Image.open(assets/'intro-grab.webp').convert('RGBA')
    alpha = grab.getchannel('A')
    for name, color in FLATS.items():
        flat = Image.new('RGBA', grab.size, color)
        flat.putalpha(alpha)
        flat.save(OUT/f'assets/intro-flat-{name}.png', optimize=True)
    # fx.js prepareGrab 'multiply' copies: one channel each, drawn back with 'lighter'
    for i, name in enumerate('rgb'):
        bands = [grab.getchannel(i) if j == i else Image.new('L', grab.size, 0) for j in range(3)]
        Image.merge('RGBA', bands + [alpha]).save(OUT/f'assets/intro-channel-{name}.webp', quality=90, method=6)
    # capri.js buildAlphaMap (cut-out plus the mirrored arm), thresholded like hit()/buildHull: alpha > 40
    sprite = Image.open(assets/'capri-full.png').convert('RGBA')
    w, h = sprite.size
    a = sprite.getchannel('A').load()
    opaque = [[a[x, y] > 40 for x in range(w)] for y in range(h)]
    for y in range(h):
        for x in range(w):
            if arm_l(x, y) and 234 - x < w and a[x, y] > 40: opaque[y][234 - x] = True
    rows = []
    for row in opaque:
        runs, x = [], 0
        while x < w:
            if row[x]:
                start = x
                while x < w and row[x]: x += 1
                runs += [start, x]
            x += 1
        rows.append(runs)
    (OUT/'js/alpha.mjs').write_text('// Generated by scripts/build-capri-assets.py: per sprite row, [start, end) runs where alpha > 40.\n'
                                    'export const ALPHA_ROWS = ' + json.dumps(rows, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    build(Path(sys.argv[1] if len(sys.argv) > 1 else Path.home()/'Projects/capri/upstream').expanduser())
